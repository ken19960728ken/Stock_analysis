def normalize_sector(raw_name: str) -> str:
    """將 FinMind 的 industry_category 標準化為 TWSE 產業大類名稱"""
    if not raw_name or not isinstance(raw_name, str):
        return raw_name
    name = raw_name.strip()
    return INDUSTRY_ALIAS_MAP.get(name, name)
